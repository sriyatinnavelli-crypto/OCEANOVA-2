  function loadCreatures() {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved) {
        creatures = JSON.parse(saved);
      } else if (typeof DEFAULT_CREATURES !== 'undefined') {
        creatures = JSON.parse(JSON.stringify(DEFAULT_CREATURES));
      }
    } catch (e) {
      console.warn('Falling back to default creatures', e);
      creatures = typeof DEFAULT_CREATURES !== 'undefined' ? DEFAULT_CREATURES : [];
    }

    if (!creatures || creatures.length === 0) {
      fetchCreaturesFallback();
    }

    // Sort by depth ascending
    creatures.sort((a, b) => a.depth - b.depth);
  }

  function fetchCreaturesFallback() {
    const urls = ['creatures.json', 'data/creatures.json'];
    function tryNext(idx) {
      if (idx >= urls.length) return;
      fetch(urls[idx])
        .then(r => {
          if (!r.ok) throw new Error('Not found');
          return r.json();
        })
        .then(data => {
          if (Array.isArray(data) && data.length > 0) {
            creatures = data;
            creatures.sort((a, b) => a.depth - b.depth);
            buildLayout();
            renderSpecimensTable();
          }
        })
        .catch(() => tryNext(idx + 1));
    }
    tryNext(0);
  }

