  function calculateCurrentDepth() {
    const scrollY = window.scrollY || window.pageYOffset || 0;
    const pxPerM = config.pxPerMeter;

    if (scrollY <= HERO_HEIGHT) {
      // Linear proportion inside hero
      return Math.max(0, Math.round((scrollY / HERO_HEIGHT) * 10));
    }

    const descentScroll = scrollY - HERO_HEIGHT;
    const depth = Math.round(descentScroll / pxPerM);
    return Math.min(MAX_DEPTH, Math.max(0, depth));
  }

  function getZoneAtDepth(depth) {
    const zones = getZones();
    if (depth < 200) return zones[0];
    if (depth < 1000) return zones[1];
    if (depth < 4000) return zones[2];
    if (depth < 6000) return zones[3];
    return zones[4];
  }

  function updateTelemetryOnScroll() {
    const depth = calculateCurrentDepth();
    const feet = Math.round(depth * 3.28084);

    // 1. Update Depth Display
    if (config.primaryUnit === 'feet') {
      depthMetersEl.textContent = feet.toLocaleString();
      primaryUnitEl.textContent = 'ft';
      secondaryDepthWrap.innerHTML = `<span>${depth.toLocaleString()}</span> m`;
    } else {
      depthMetersEl.textContent = depth.toLocaleString();
      primaryUnitEl.textContent = 'm';
      secondaryDepthWrap.innerHTML = `<span>${feet.toLocaleString()}</span> ft`;
    }

    // 2. Zone Detection & Badge
    const zone = getZoneAtDepth(depth);
    hudZoneName.textContent = zone.name.toUpperCase();

    // 3. Environmental Calculations
    // Hydrostatic pressure: 1 atm at surface, +1 atm roughly every 10 meters
    const pressure = (1 + (depth * 0.1)).toFixed(1);
    telemPressure.textContent = `${parseFloat(pressure).toLocaleString()} atm`;

    // Temperature: 24C at surface down to ~1.4C at bottom
    let temp = 24.0;
    if (depth <= 200) {
      temp = 24 - ((depth / 200) * 12); // 24C to 12C
    } else if (depth <= 1000) {
      temp = 12 - (((depth - 200) / 800) * 8); // 12C to 4C
    } else if (depth <= 4000) {
      temp = 4 - (((depth - 1000) / 3000) * 2.5); // 4C to 1.5C
    } else {
      temp = 1.5 - (((depth - 4000) / 7000) * 0.4); // 1.5C to 1.1C
    }
    telemTemp.textContent = `${temp.toFixed(1)}°C`;

    // 4. Dynamic Water Background Gradient
    interpolateOceanBackground(depth);
  }

  function interpolateOceanBackground(depth) {
    // Determine gradient colors based on depth milestones
    let color;
    if (depth <= 100) {
      color = '#48b5e4';
    } else if (depth <= 200) {
      color = '#257ba8';
    } else if (depth <= 500) {
      color = '#16537e';
    } else if (depth <= 1000) {
      color = '#0d325c';
    } else if (depth <= 2000) {
      color = '#081a30';
    } else if (depth <= 4000) {
      color = '#030a14';
    } else if (depth <= 6000) {
      color = '#02070e';
    } else if (depth <= 9000) {
      color = '#010306';
    } else {
      color = '#000000';
    }

    document.body.style.backgroundColor = color;
  }

