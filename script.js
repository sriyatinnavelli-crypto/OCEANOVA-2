  function toggleAudio() {
    if (!audioContext) {
      const AudioCtx = window.AudioContext || window.webkitAudioContext;
      audioContext = new AudioCtx();
      createUnderwaterSoundscape();
    }

    if (audioContext.state === 'suspended') {
      audioContext.resume();
    }

    isAudioPlaying = !isAudioPlaying;

    if (isAudioPlaying) {
      audioNodes.masterGain.gain.setTargetAtTime(0.4, audioContext.currentTime, 0.5);
      btnSound.querySelector('.btn-icon').textContent = '🔊';
      btnSound.querySelector('.btn-text').textContent = 'Audio ON';
      scheduleSonarPing();
    } else {
      audioNodes.masterGain.gain.setTargetAtTime(0, audioContext.currentTime, 0.5);
      btnSound.querySelector('.btn-icon').textContent = '🔇';
      btnSound.querySelector('.btn-text').textContent = 'Audio';
    }
  }

  function createUnderwaterSoundscape() {
    const ctx = audioContext;
    const masterGain = ctx.createGain();
    masterGain.gain.setValueAtTime(0, ctx.currentTime);
    masterGain.connect(ctx.destination);
    audioNodes.masterGain = masterGain;

    // 1. Deep Ocean Brown Noise Rumble Generator
    const bufferSize = ctx.sampleRate * 2;
    const noiseBuffer = ctx.createBuffer(1, bufferSize, ctx.sampleRate);
    const output = noiseBuffer.getChannelData(0);
    let lastOut = 0.0;
    for (let i = 0; i < bufferSize; i++) {
      const white = Math.random() * 2 - 1;
      output[i] = (lastOut + (0.02 * white)) / 1.02;
      lastOut = output[i];
      output[i] *= 3.5; // Gain compensation
    }

    const whiteNoise = ctx.createBufferSource();
    whiteNoise.buffer = noiseBuffer;
    whiteNoise.loop = true;

    // Low-pass filter to sound deeply submerged
    const lowpass = ctx.createBiquadFilter();
    lowpass.type = 'lowpass';
    lowpass.frequency.setValueAtTime(140, ctx.currentTime);

    const noiseGain = ctx.createGain();
    noiseGain.gain.setValueAtTime(0.7, ctx.currentTime);

    whiteNoise.connect(lowpass);
    lowpass.connect(noiseGain);
    noiseGain.connect(masterGain);
    whiteNoise.start();

    // 2. Sub-bass resonance drone
    const subOsc = ctx.createOscillator();
    subOsc.type = 'sine';
    subOsc.frequency.setValueAtTime(45, ctx.currentTime);

    const subGain = ctx.createGain();
    subGain.gain.setValueAtTime(0.3, ctx.currentTime);

    subOsc.connect(subGain);
    subGain.connect(masterGain);
    subOsc.start();
  }

  function scheduleSonarPing() {
    if (!isAudioPlaying || !audioContext) return;

    // Random sonar ping every 10-18 seconds
    const delay = 10000 + Math.random() * 8000;
    setTimeout(() => {
      if (isAudioPlaying) {
        playSonarPing();
        scheduleSonarPing();
      }
    }, delay);
  }

  function playSonarPing() {
    if (!audioContext || !audioNodes.masterGain) return;
    const ctx = audioContext;

    const osc = ctx.createOscillator();
    const gain = ctx.createGain();

    osc.type = 'sine';
    osc.frequency.setValueAtTime(800, ctx.currentTime);
    osc.frequency.exponentialRampToValueAtTime(750, ctx.currentTime + 1.2);

    gain.gain.setValueAtTime(0.08, ctx.currentTime);
    gain.gain.exponentialRampToValueAtTime(0.0001, ctx.currentTime + 1.5);

    osc.connect(gain);
    gain.connect(audioNodes.masterGain);

    osc.start();
    osc.stop(ctx.currentTime + 1.6);
  }

  // --------------------------------------------------------------------------
  // CANVAS PARTICLES (Marine Snow & Bubbles)
  // --------------------------------------------------------------------------
  function initCanvasParticles() {
    if (config.particles === 'off') {
      ambientCanvas.style.display = 'none';
      return;
    }

    ambientCanvas.style.display = 'block';
    const ctx = ambientCanvas.getContext('2d');
    let width = (ambientCanvas.width = window.innerWidth);
    let height = (ambientCanvas.height = window.innerHeight);

    window.addEventListener('resize', () => {
      width = ambientCanvas.width = window.innerWidth;
      height = ambientCanvas.height = window.innerHeight;
    });

    const particles = [];
    const count = 70;

    for (let i = 0; i < count; i++) {
      particles.push({
        x: Math.random() * width,
        y: Math.random() * height,
        radius: Math.random() * 2 + 0.6,
        speedY: (Math.random() * 0.4 + 0.1) * (Math.random() > 0.3 ? -1 : 1), // Mostly float up
        speedX: (Math.random() - 0.5) * 0.3,
        alpha: Math.random() * 0.6 + 0.2,
        isBubble: Math.random() > 0.7
      });
    }

    function animateParticles() {
      ctx.clearRect(0, 0, width, height);

      particles.forEach(p => {
        p.y += p.speedY;
        p.x += p.speedX;

        // Wrap around boundaries
        if (p.y < 0) p.y = height;
        if (p.y > height) p.y = 0;
        if (p.x < 0) p.x = width;
        if (p.x > width) p.x = 0;

        ctx.beginPath();
        ctx.arc(p.x, p.y, p.radius, 0, Math.PI * 2);

        if (p.isBubble) {
          ctx.strokeStyle = `rgba(128, 222, 234, ${p.alpha * 0.6})`;
          ctx.lineWidth = 1;
          ctx.stroke();
        } else {
          ctx.fillStyle = `rgba(255, 255, 255, ${p.alpha * 0.5})`;
          ctx.fill();
        }
      });

      requestAnimationFrame(animateParticles);
    }

    animateParticles();
  }

